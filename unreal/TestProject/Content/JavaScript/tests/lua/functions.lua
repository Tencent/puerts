local f = require('tests/lua/framework')
local UE, puerts, test, eq, assert, observe = f.UE, f.puerts, f.test, f.eq, f.assert, f.observe
local ref, unref = puerts.ref, puerts.unref

local obj = UE.PuertsTestObject()

test('member call', function()
    eq(obj:Add(1, 2), 3)
    eq(obj:Concat('a', 'b'), 'ab')
end)

test('static call', function()
    eq(UE.PuertsTestObject.StaticAdd(4, 5), 9)
    observe('static via instance', function()
        return type(obj.StaticAdd)
    end)
end)

test('return struct', function()
    local s = obj:MakeStruct(3, 'x')
    eq(s.X, 3)
    eq(s.S, 'x')
    eq(s.Arr:Num(), 3)
    eq(s.Arr:Get(2), 5)
end)

test('struct param', function()
    local s = UE.PuertsTestStruct()
    s.X = 1
    s.Arr:Add(2)
    s.Arr:Add(3)
    eq(obj:StructSum(s), 6)
end)

test('out params', function()
    local i = ref(0)
    local s = ref('')
    local st = ref(UE.PuertsTestStruct())
    obj:OutParams(i, s, st)
    eq(unref(i), 7)
    eq(unref(s), 'out')
    eq(unref(st).X, 9)
    eq(unref(st).S, 'outstruct')
    observe('out struct ref nil', function()
        local u = ref(nil)
        obj:OutParams(ref(0), ref(''), u)
        return unref(u) and unref(u).X
    end)
end)

test('ref param', function()
    local v = ref(41)
    obj:IncRef(v)
    eq(unref(v), 42)
    local w = ref(1)
    puerts.setref(w, 9)
    obj:IncRef(w)
    eq(unref(w), 10)
end)

test('default param', function()
    eq(obj:DefaultParam(3, 4), 304)
    observe('default param omitted', function()
        return obj:DefaultParam(3)
    end)
end)

test('object return identity', function()
    assert(obj:GetSelf() == obj, 'GetSelf returns same lua object')
    local c = obj:CreateChild()
    assert(c ~= obj:CreateChild(), 'distinct children')
    eq(c:GetOuter() == obj, true, 'outer')
end)

test('array param', function()
    local a = UE.NewArray(UE.BuiltinInt)
    a:Add(1)
    a:Add(2)
    a:Add(3)
    eq(obj:SumArray(a), 6)
    local out = ref(UE.NewArray(UE.BuiltinInt))
    obj:FillArray(out, 4)
    local filled = unref(out)
    eq(filled:Num(), 4)
    eq(filled:Get(3), 3)
end)

test('map return', function()
    local m = obj:MakeMap(3)
    eq(m:Num(), 3)
    eq(m:Get('k2'), 2)
end)

test('enum param/return', function()
    eq(obj:NextEnum(UE.EPuertsTestEnum.A), UE.EPuertsTestEnum.B)
    eq(obj:NextEnum(UE.EPuertsTestEnum.B), UE.EPuertsTestEnum.C)
end)

test('text return', function()
    eq(obj:MakeText('t'), 't')
end)

test('native event default', function()
    eq(obj:CallNativeEvent('a'), 'native:a')
    observe('impl event without override', function()
        return obj:CallImplEvent(1)
    end)
end)

test('function shape', function()
    observe('method type', function()
        return type(obj.Add)
    end)
    observe('method called with a dot', function()
        return obj.Add(1, 2)
    end)
end)

test('UE builtin', function()
    eq(UE.KismetMathLibrary.Add_IntInt(2, 3), 5)
    observe('GameplayStatics available', function()
        return UE.GameplayStatics ~= nil
    end)
end)

f.run()
